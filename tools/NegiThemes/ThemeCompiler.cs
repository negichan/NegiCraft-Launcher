using System.Security.Cryptography;
using System.Text;
using System.Xml;
using System.Xml.Linq;

namespace NegiThemes;

internal sealed class ThemeCompiler
{
    public string Compile(string sourcePath, string repositoryRoot)
    {
        var source = XDocument.Load(sourcePath, LoadOptions.SetLineInfo);
        var session = new CompileSession(source);

        var root = new XElement(CompileSession.Avalonia + "ResourceDictionary",
            new XAttribute(XNamespace.Xmlns + "x", CompileSession.X.NamespaceName),
            new XAttribute(XNamespace.Xmlns + "conv", "using:Avalonia.Data.Converters"));

        var relativeSource = Path.GetRelativePath(repositoryRoot, sourcePath).Replace('\\', '/');
        var hash = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(sourcePath)))[..12].ToLowerInvariant();
        root.Add(new XComment(
            $" <auto-generated> from {relativeSource} (sha256 {hash}); do not edit by hand. " +
            "Regenerate with tools/NegiThemes. </auto-generated> "));

        var generated = 0;
        foreach (var adapter in CreateAdapters())
        {
            foreach (var theme in adapter.Compile(session))
            {
                root.Add(theme);
                generated++;
            }
        }

        session.EnsureEverythingConsumed();

        foreach (var note in session.Notes)
            root.Add(new XComment($" {note} "));

        if (generated == 0)
            throw new InvalidOperationException("No control themes were generated.");

        Console.WriteLine($"  generated {generated} theme(s)");

        var document = new XDocument(new XDeclaration("1.0", "utf-8", null), root);
        using var writer = new Utf8StringWriter();
        using (var xml = XmlWriter.Create(writer, new XmlWriterSettings
               {
                   Indent = true,
                   IndentChars = "    ",
                   NewLineChars = "\n",
                   NewLineOnAttributes = true,
                   OmitXmlDeclaration = false,
               }))
        {
            document.Save(xml);
        }

        return writer.ToString();
    }

    private static IControlAdapter[] CreateAdapters() =>
    [
        new GenericAdapter("RepeatButton", "RepeatButton"),
        new GenericAdapter("Thumb", "Thumb"),
        new GenericAdapter("Button", "Button", new GenericOptions
        {
            DropButtonMotion = true,
        }),
        new GenericAdapter("ProgressBar", "ProgressBar", new GenericOptions
        {
            SkipTrigger = trigger => (string?)trigger.Attribute("Property") == "IsIndeterminate",
        }),
        new GenericAdapter("ItemsControl", "ItemsControl", new GenericOptions
        {
            AdaptTemplateElement = (_, target) =>
            {
                if (target.Name.LocalName == "ItemsPresenter")
                    target.SetAttributeValue("ItemsPanel", "{TemplateBinding ItemsPanel}");
            },
        }),
        new GenericAdapter("Separator", "Separator", new GenericOptions
        {
            SkipMarkupKeyStyles = true,
        }),
        new TextBoxAdapter(),
        new SwitchAdapter(),
        new SliderAdapter(),
        new ScrollBarAdapter(),
        new ScrollViewerAdapter(),
        new ToolTipAdapter(),
        new MenuFlyoutAdapter(),
        new MenuItemAdapter(),
    ];

    private sealed class Utf8StringWriter : StringWriter
    {
        public override Encoding Encoding => new UTF8Encoding(encoderShouldEmitUTF8Identifier: false);
    }
}
